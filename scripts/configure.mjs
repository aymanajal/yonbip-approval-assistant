import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname,resolve} from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const input=resolve(process.cwd(),process.argv[2]||'config.local.json');
try {
  const config=JSON.parse(readFileSync(input,'utf8'));
  if(!Array.isArray(config.origins)||!config.origins.length)throw Error('origins 必须是非空数组');
  const origins=[...new Set(config.origins.map(value=>{
    if(typeof value!=='string')throw Error('环境地址必须是字符串');
    const url=new URL(value);
    if(!['http:','https:'].includes(url.protocol)||url.username||url.password||url.search||url.hash||url.pathname!=='/'||url.hostname.includes('*'))throw Error('仅支持不含账号、密码、路径、查询参数或通配符的 HTTP/HTTPS 来源地址');
    return url.origin;
  }))];
  const manifest=JSON.parse(readFileSync(resolve(root,'manifest.json'),'utf8'));
  manifest.content_scripts[0].matches=origins.map(origin=>origin+'/nccloud/resources/ssctp/sscuser/sscapprove/list/*');
  manifest.web_accessible_resources[0].matches=origins.map(origin=>origin+'/*');
  writeFileSync(resolve(root,'config.js'),'// Generated by scripts/configure.mjs\nglobalThis.APPROVAL_ORIGINS = Object.freeze('+JSON.stringify(origins)+');\n');
  writeFileSync(resolve(root,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');
  console.log(`已配置 ${origins.length} 个环境。请重新加载扩展并刷新审批页。`);
} catch(error) {console.error('配置失败：'+error.message);process.exitCode=1;}
